#!/usr/bin/env python3
from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from datetime import datetime, timedelta, timezone
from pathlib import Path
from typing import Any


DEFAULT_AUDIT_DIR = Path(".codex/comment-audits")
DEFAULT_CHECKPOINT = DEFAULT_AUDIT_DIR / "checkpoint.json"
DEFAULT_RESULTS = DEFAULT_AUDIT_DIR / "results.jsonl"
DEFAULT_BOT_LOGINS = ("gitdogbot[bot]", "gitdogbot-dev[bot]")
FOOTER_MARKERS = ("Generated by [gitdog.dev]",)
ISSUE_COMMENT_URL_RE = re.compile(
    r"^https?://github\.com/(?P<owner>[^/]+)/(?P<name>[^/]+)/"
    r"(?:(?:issues|pull)/\d+/?(?:\?[^#]*)?#issuecomment-|"
    r"discussions/\d+/?(?:\?[^#]*)?#discussioncomment-)"
    r"(?P<comment_id>\d+)$",
    re.IGNORECASE,
)
DISCUSSION_COMMENT_URL_RE = re.compile(
    r"^https?://github\.com/[^/]+/[^/]+/discussions/\d+/?(?:\?[^#]*)?#discussioncomment-\d+$",
    re.IGNORECASE,
)

DISCUSSIONS_QUERY = """
query($owner:String!, $name:String!, $first:Int!, $after:String) {
  repository(owner: $owner, name: $name) {
    discussions(first: $first, after: $after, orderBy: {field: UPDATED_AT, direction: DESC}) {
      pageInfo {
        hasNextPage
        endCursor
      }
      nodes {
        number
        title
        url
        updatedAt
        comments(last: 100) {
          totalCount
          pageInfo {
            hasPreviousPage
            startCursor
          }
          nodes {
            id
            databaseId
            body
            url
            createdAt
            updatedAt
            author {
              login
            }
            replies(last: 100) {
              totalCount
              pageInfo {
                hasPreviousPage
                startCursor
              }
              nodes {
                id
                databaseId
                body
                url
                createdAt
                updatedAt
                author {
                  login
                }
              }
            }
          }
        }
      }
    }
  }
}
"""


def utc_now() -> datetime:
    return datetime.now(timezone.utc)


def iso_z(value: datetime) -> str:
    return (
        value.astimezone(timezone.utc)
        .replace(microsecond=0)
        .isoformat()
        .replace("+00:00", "Z")
    )


def parse_time(value: str) -> datetime:
    normalized = value.strip().replace("Z", "+00:00")
    return datetime.fromisoformat(normalized).astimezone(timezone.utc)


def read_json(path: Path) -> dict[str, Any]:
    if not path.exists():
        return {"version": 1, "repos": {}}
    return json.loads(path.read_text(encoding="utf-8"))


def write_json(path: Path, data: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp_path = path.with_suffix(f"{path.suffix}.tmp")
    tmp_path.write_text(
        json.dumps(data, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )
    tmp_path.replace(path)


def run_gh_json(args: list[str]) -> Any:
    command = ["gh", *args]
    try:
        completed = subprocess.run(
            command,
            check=False,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True,
        )
    except FileNotFoundError as error:
        raise RuntimeError("GitHub CLI `gh` is required for this script") from error

    if completed.returncode != 0:
        joined = " ".join(command)
        raise RuntimeError(f"`{joined}` failed: {completed.stderr.strip()}")

    output = completed.stdout.strip()
    if not output:
        return None

    try:
        return json.loads(output)
    except json.JSONDecodeError as error:
        joined = " ".join(command)
        raise RuntimeError(f"`{joined}` did not return valid JSON") from error


def infer_repo() -> str:
    result = run_gh_json(["repo", "view", "--json", "nameWithOwner"])
    repo = result.get("nameWithOwner") if isinstance(result, dict) else None
    if not repo:
        raise RuntimeError("Could not infer repository. Pass --repo owner/repo.")
    return repo


def split_repo(repo: str) -> tuple[str, str]:
    parts = repo.split("/", 1)
    if len(parts) != 2 or not parts[0] or not parts[1]:
        raise ValueError("Repository must be in owner/repo format")
    return parts[0], parts[1]


def normalize_repo_name(repo: str) -> str:
    return repo.strip().lower()


def find_checkpoint_repo_key(repos: dict[str, Any], repo: str) -> str | None:
    normalized = normalize_repo_name(repo)
    if normalized in repos:
        return normalized
    for key in repos:
        if normalize_repo_name(key) == normalized:
            return key
    return None


def canonicalize_checkpoint_repo_key(checkpoint: dict[str, Any], repo: str) -> str:
    normalized = normalize_repo_name(repo)
    repos = checkpoint.setdefault("repos", {})
    existing_key = find_checkpoint_repo_key(repos, normalized)
    if existing_key and existing_key != normalized:
        repos[normalized] = repos.pop(existing_key)
    return normalized


def normalize_bot_logins(value: str | None) -> set[str]:
    if not value:
        return {login.lower() for login in DEFAULT_BOT_LOGINS}
    return {part.strip().lower() for part in value.split(",") if part.strip()}


def is_gitdog_comment(login: str | None, body: str, bot_logins: set[str]) -> bool:
    normalized_login = (login or "").lower()
    if normalized_login in bot_logins:
        return True
    lower_body = body.lower()
    return any(marker.lower() in lower_body for marker in FOOTER_MARKERS)


def is_gitdog_footer_tail(tail: str) -> bool:
    normalized = tail.strip().lower().lstrip("*_ ")
    return any(
        normalized.startswith(marker.lower()) for marker in FOOTER_MARKERS
    )


def body_without_footer(body: str) -> str:
    separator_matches = list(re.finditer(r"\r?\n-{3,}\r?\n", body))
    if separator_matches:
        last_match = separator_matches[-1]
        if is_gitdog_footer_tail(body[last_match.end() :]):
            return body[: last_match.start()].rstrip()
    return body.rstrip()


def issue_number_from_url(issue_url: str) -> int | None:
    match = re.search(r"/issues/(\d+)$", issue_url)
    return int(match.group(1)) if match else None


def parse_issue_comment_url(value: str) -> tuple[str, int] | None:
    match = ISSUE_COMMENT_URL_RE.match(value.strip())
    if not match:
        return None
    repo = f"{match.group('owner')}/{match.group('name')}"
    return repo, int(match.group("comment_id"))


def is_discussion_comment_url(value: str) -> bool:
    return bool(DISCUSSION_COMMENT_URL_RE.match(value.strip()))


def flatten_pages(payload: Any) -> list[dict[str, Any]]:
    if payload is None:
        return []
    if isinstance(payload, list) and all(isinstance(page, list) for page in payload):
        return [item for page in payload for item in page]
    if isinstance(payload, list):
        return [item for item in payload if isinstance(item, dict)]
    raise RuntimeError("Unexpected GitHub pagination payload")


def make_issue_record(repo: str, comment: dict[str, Any]) -> dict[str, Any] | None:
    body = comment.get("body") or ""
    issue_number = issue_number_from_url(comment.get("issue_url") or "")
    if issue_number is None:
        return None

    comment_id = comment.get("id")
    return {
        "key": f"issue_comment:{comment_id}",
        "type": "issue_comment",
        "repo": repo,
        "issue_number": issue_number,
        "comment_id": comment_id,
        "node_id": comment.get("node_id"),
        "url": comment.get("html_url"),
        "author": (comment.get("user") or {}).get("login"),
        "created_at": comment.get("created_at"),
        "updated_at": comment.get("updated_at"),
        "body": body,
        "body_without_footer": body_without_footer(body),
    }


def collect_issue_comments(
    repo: str,
    since: datetime,
    bot_logins: set[str],
) -> list[dict[str, Any]]:
    endpoint = (
        f"/repos/{repo}/issues/comments"
        f"?per_page=100&since={iso_z(since)}&sort=updated&direction=asc"
    )
    payload = run_gh_json(["api", "--paginate", "--slurp", endpoint])
    records: list[dict[str, Any]] = []
    for comment in flatten_pages(payload):
        body = comment.get("body") or ""
        login = (comment.get("user") or {}).get("login")
        updated_at = comment.get("updated_at")
        if updated_at and parse_time(updated_at) < since:
            continue
        if not is_gitdog_comment(login, body, bot_logins):
            continue
        record = make_issue_record(repo, comment)
        if record:
            records.append(record)
    return records


def collect_issue_comment_url(
    url: str,
    repo: str | None,
    bot_logins: set[str],
) -> tuple[str, dict[str, Any]]:
    if is_discussion_comment_url(url):
        raise ValueError(
            "--url collect currently supports only issue or pull request issue-comment URLs"
        )
    parsed = parse_issue_comment_url(url)
    if not parsed:
        raise ValueError(
            "--url currently supports GitHub issue or pull request issue-comment URLs"
        )

    url_repo, comment_id = parsed
    if repo and normalize_repo_name(repo) != normalize_repo_name(url_repo):
        raise ValueError(f"--repo {repo} does not match URL repository {url_repo}")

    resolved_repo = normalize_repo_name(repo or url_repo)
    comment = run_gh_json(
        ["api", f"/repos/{resolved_repo}/issues/comments/{comment_id}"]
    )
    if not comment:
        raise RuntimeError(f"Could not fetch comment {comment_id} from GitHub API")

    record = make_issue_record(resolved_repo, comment)
    if not record:
        raise RuntimeError(f"Could not build an issue comment record for {url}")

    if not is_gitdog_comment(record.get("author"), record.get("body") or "", bot_logins):
        raise RuntimeError(
            "Comment is not from a configured Gitdog login and has no Gitdog footer. "
            "Pass --bot-logins to audit a different bot."
        )

    return resolved_repo, record


def discussion_comment_record(
    repo: str,
    discussion: dict[str, Any],
    comment: dict[str, Any],
    record_type: str,
    parent_node_id: str | None = None,
) -> dict[str, Any]:
    body = comment.get("body") or ""
    node_id = comment.get("id")
    return {
        "key": f"{record_type}:{node_id}",
        "type": record_type,
        "repo": repo,
        "discussion_number": discussion.get("number"),
        "discussion_title": discussion.get("title"),
        "discussion_url": discussion.get("url"),
        "comment_id": comment.get("databaseId"),
        "node_id": node_id,
        "parent_node_id": parent_node_id,
        "url": comment.get("url"),
        "author": (comment.get("author") or {}).get("login"),
        "created_at": comment.get("createdAt"),
        "updated_at": comment.get("updatedAt"),
        "body": body,
        "body_without_footer": body_without_footer(body),
    }


def collect_discussion_comments(
    repo: str,
    since: datetime,
    bot_logins: set[str],
    max_discussions: int,
) -> tuple[list[dict[str, Any]], list[str]]:
    owner, name = split_repo(repo)
    records: list[dict[str, Any]] = []
    warnings: list[str] = []
    cursor: str | None = None
    scanned = 0

    while scanned < max_discussions:
        first = min(50, max_discussions - scanned)
        args = [
            "api",
            "graphql",
            "-f",
            f"query={DISCUSSIONS_QUERY}",
            "-F",
            f"owner={owner}",
            "-F",
            f"name={name}",
            "-F",
            f"first={first}",
        ]
        if cursor:
            args.extend(["-F", f"after={cursor}"])

        payload = run_gh_json(args)
        discussions = (
            ((payload or {}).get("data") or {})
            .get("repository", {})
            .get("discussions", {})
        )
        nodes = discussions.get("nodes") or []
        if not nodes:
            break

        should_continue = bool(discussions.get("pageInfo", {}).get("hasNextPage"))
        cursor = discussions.get("pageInfo", {}).get("endCursor")

        for discussion in nodes:
            scanned += 1
            discussion_updated_at = discussion.get("updatedAt")
            if discussion_updated_at and parse_time(discussion_updated_at) < since:
                should_continue = False
                continue

            comments = discussion.get("comments") or {}
            if comments.get("totalCount", 0) > len(comments.get("nodes") or []):
                warnings.append(
                    f"Discussion #{discussion.get('number')} has more than 100 comments; collection used the newest 100."
                )

            for comment in comments.get("nodes") or []:
                body = comment.get("body") or ""
                login = (comment.get("author") or {}).get("login")
                updated_at = comment.get("updatedAt")
                if updated_at and parse_time(updated_at) >= since:
                    if is_gitdog_comment(login, body, bot_logins):
                        records.append(
                            discussion_comment_record(
                                repo,
                                discussion,
                                comment,
                                "discussion_comment",
                            )
                        )

                replies = comment.get("replies") or {}
                if replies.get("totalCount", 0) > len(replies.get("nodes") or []):
                    warnings.append(
                        f"Discussion #{discussion.get('number')} comment {comment.get('id')} has more than 100 replies; collection used the newest 100."
                    )

                for reply in replies.get("nodes") or []:
                    reply_body = reply.get("body") or ""
                    reply_login = (reply.get("author") or {}).get("login")
                    reply_updated_at = reply.get("updatedAt")
                    if reply_updated_at and parse_time(reply_updated_at) < since:
                        continue
                    if not is_gitdog_comment(reply_login, reply_body, bot_logins):
                        continue
                    records.append(
                        discussion_comment_record(
                            repo,
                            discussion,
                            reply,
                            "discussion_reply",
                            parent_node_id=comment.get("id"),
                        )
                    )

        if not should_continue:
            break

    return records, warnings


def safe_repo_name(repo: str) -> str:
    return repo.replace("/", "__")


def sort_records(records: list[dict[str, Any]]) -> list[dict[str, Any]]:
    return sorted(
        records,
        key=lambda record: (
            record.get("updated_at") or "",
            record.get("type") or "",
            record.get("key") or "",
        ),
    )


def write_jsonl(path: Path, records: list[dict[str, Any]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as handle:
        for record in records:
            handle.write(json.dumps(record, sort_keys=True) + "\n")


def latest_repo_result_entries(results_path: Path, repo: str) -> list[dict[str, Any]]:
    if not results_path.is_file():
        return []

    normalized_repo = normalize_repo_name(repo)
    latest_by_item: dict[str, dict[str, Any]] = {}
    with results_path.open(encoding="utf-8") as handle:
        for line in handle:
            line = line.strip()
            if not line:
                continue
            try:
                entry = json.loads(line)
            except json.JSONDecodeError:
                continue
            if not isinstance(entry, dict):
                continue
            entry_repo = entry.get("repo")
            if (
                not isinstance(entry_repo, str)
                or normalize_repo_name(entry_repo) != normalized_repo
            ):
                continue
            item = entry.get("item")
            if not isinstance(item, str) or not item:
                continue
            latest_by_item[item] = entry
    return list(latest_by_item.values())


def latest_repo_audit_counts(results_path: Path, repo: str) -> dict[str, int]:
    counts: dict[str, int] = {}
    for entry in latest_repo_result_entries(results_path, repo):
        status = entry.get("status")
        if not isinstance(status, str) or not status:
            continue
        counts[status] = counts.get(status, 0) + 1
    return counts


def resolve_since(
    args: argparse.Namespace,
    checkpoint: dict[str, Any],
    repo: str,
) -> datetime:
    if args.since:
        return parse_time(args.since)
    if args.latest:
        return utc_now() - timedelta(hours=args.lookback_hours)
    repo_state = checkpoint.get("repos", {}).get(repo, {})
    if repo_state.get("last_checked_at"):
        return parse_time(repo_state["last_checked_at"])
    return utc_now() - timedelta(hours=args.lookback_hours)


def command_collect(args: argparse.Namespace) -> int:
    checkpoint_path = Path(args.checkpoint)
    checkpoint = read_json(checkpoint_path)
    run_started = utc_now()
    bot_logins = normalize_bot_logins(args.bot_logins)

    records: list[dict[str, Any]] = []
    warnings: list[str] = []
    collection_from: str
    repo: str

    if args.url:
        repo, record = collect_issue_comment_url(args.url, args.repo, bot_logins)
        repo = canonicalize_checkpoint_repo_key(checkpoint, repo)
        records.append(record)
        collection_from = (
            record.get("updated_at")
            or record.get("created_at")
            or iso_z(run_started)
        )
    else:
        repo = canonicalize_checkpoint_repo_key(checkpoint, args.repo or infer_repo())
        since = resolve_since(args, checkpoint, repo)
        collection_from = iso_z(since)

        if args.types in ("all", "issues"):
            records.extend(collect_issue_comments(repo, since, bot_logins))

        if args.types in ("all", "discussions"):
            discussion_records, discussion_warnings = collect_discussion_comments(
                repo,
                since,
                bot_logins,
                args.max_discussions,
            )
            records.extend(discussion_records)
            warnings.extend(discussion_warnings)

    sorted_records = sort_records(records)
    if args.latest and not args.url:
        sorted_records = sorted_records[-args.limit :]
    output_path = (
        Path(args.out)
        if args.out
        else (
            DEFAULT_AUDIT_DIR
            / f"{safe_repo_name(repo)}-{sorted_records[0]['key'].replace(':', '-')}.jsonl"
            if args.url and sorted_records
            else DEFAULT_AUDIT_DIR
            / f"{safe_repo_name(repo)}-{iso_z(run_started).replace(':', '')}.jsonl"
        )
    )
    write_jsonl(output_path, sorted_records)

    repos = checkpoint.setdefault("repos", {})
    repo_state = repos.setdefault(repo, {})
    if not args.url:
        repo_state["last_checked_at"] = iso_z(run_started)
    repo_state["last_collection"] = {
        "from": collection_from,
        "to": iso_z(run_started),
        "completed_at": iso_z(utc_now()),
        "output": str(output_path),
        "items": len(sorted_records),
        "latest": args.latest,
        "limit": args.limit if args.latest else None,
        "types": args.types,
        "url": args.url,
        "bot_logins": sorted(bot_logins),
        "warnings": warnings,
    }
    repo_state["last_collection_output"] = str(output_path)
    write_json(checkpoint_path, checkpoint)

    print(f"Collected {len(sorted_records)} Gitdog comments for {repo}")
    print(f"Window: {collection_from} -> {iso_z(run_started)}")
    print(f"Output: {output_path}")
    print(f"Checkpoint: {checkpoint_path}")
    for warning in warnings:
        print(f"Warning: {warning}", file=sys.stderr)
    return 0


def summarize_repo_state(repo: str, state: dict[str, Any]) -> dict[str, Any]:
    audit_counts = state.get("audit_counts", {})
    results_path = state.get("last_audit_results_path")
    if isinstance(results_path, str) and results_path:
        path = Path(results_path)
        if path.is_file():
            audit_counts = latest_repo_audit_counts(path, repo)

    return {
        "repo": repo,
        "last_checked_at": state.get("last_checked_at"),
        "last_collection": state.get("last_collection"),
        "last_audited_at": state.get("last_audited_at"),
        "last_audited_item": state.get("last_audited_item"),
        "last_audit_status": state.get("last_audit_status"),
        "audit_counts": audit_counts,
        "last_audit_results_path": state.get("last_audit_results_path"),
    }


def command_status(args: argparse.Namespace) -> int:
    checkpoint_path = Path(args.checkpoint)
    checkpoint = read_json(checkpoint_path)
    repos = checkpoint.get("repos", {})

    if args.repo:
        repo = normalize_repo_name(args.repo)
        state_key = find_checkpoint_repo_key(repos, repo)
        state = repos.get(state_key) if state_key else None
        if not state:
            print(f"No checkpoint for {repo}")
            return 0
        summary: Any = summarize_repo_state(normalize_repo_name(state_key), state)
    else:
        summary = [summarize_repo_state(repo, state) for repo, state in repos.items()]

    if args.json:
        print(json.dumps(summary, indent=2, sort_keys=True))
        return 0

    if isinstance(summary, list):
        if not summary:
            print(f"No comment audit checkpoint at {checkpoint_path}")
            return 0
        for repo_summary in summary:
            print_status_summary(repo_summary)
    else:
        print_status_summary(summary)
    return 0


def print_status_summary(summary: dict[str, Any]) -> None:
    print(f"Repository: {summary['repo']}")
    collection = summary.get("last_collection") or {}
    if collection:
        print(f"  Collection from: {collection.get('from')}")
        print(f"  Collection to:   {collection.get('to')}")
        print(f"  Output:          {collection.get('output')}")
        print(f"  Items:           {collection.get('items')}")
    else:
        print("  Collection:      none")
    print(f"  Last audited:    {summary.get('last_audited_item') or 'none'}")
    print(f"  Last status:     {summary.get('last_audit_status') or 'none'}")
    print(f"  Last audited at: {summary.get('last_audited_at') or 'none'}")
    print(f"  Audit counts:    {summary.get('audit_counts') or {}}")
    if summary.get("last_audit_results_path"):
        print(f"  Results:         {summary['last_audit_results_path']}")


def command_record(args: argparse.Namespace) -> int:
    checkpoint_path = Path(args.checkpoint)
    checkpoint = read_json(checkpoint_path)
    parsed_url = parse_issue_comment_url(args.url)
    if not parsed_url:
        raise ValueError(
            "--url currently supports GitHub issue or pull request issue-comment URLs"
        )
    url_repo = parsed_url[0]
    if args.repo and normalize_repo_name(args.repo) != normalize_repo_name(url_repo):
        raise ValueError(f"--repo {args.repo} does not match URL repository {url_repo}")
    repo = canonicalize_checkpoint_repo_key(
        checkpoint,
        args.repo or url_repo,
    )
    result_path = Path(args.results)
    now = iso_z(utc_now())
    entry = {
        "repo": repo,
        "item": args.item,
        "status": args.status,
        "url": args.url,
        "note": args.note,
        "recorded_at": now,
    }

    result_path.parent.mkdir(parents=True, exist_ok=True)
    with result_path.open("a", encoding="utf-8") as handle:
        handle.write(json.dumps(entry, sort_keys=True) + "\n")

    repos = checkpoint.setdefault("repos", {})
    repo_state = repos.setdefault(repo, {})
    repo_state["audit_counts"] = latest_repo_audit_counts(result_path, repo)
    repo_state["last_audited_at"] = now
    repo_state["last_audited_item"] = args.item
    repo_state["last_audit_status"] = args.status
    repo_state["last_audit_url"] = args.url
    repo_state["last_audit_note"] = args.note
    repo_state["last_audit_results_path"] = str(result_path)
    write_json(checkpoint_path, checkpoint)

    print(f"Recorded {args.status} for {args.item} in {repo}")
    print(f"Results: {result_path}")
    print(f"Checkpoint: {checkpoint_path}")
    return 0


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Collect and checkpoint Gitdog-authored GitHub comments.",
    )
    subparsers = parser.add_subparsers(dest="command", required=True)

    collect = subparsers.add_parser("collect", help="Collect candidate comments")
    collect.add_argument("--repo", help="Repository in owner/repo format")
    collect.add_argument("--since", help="ISO timestamp. Defaults to checkpoint.")
    collect.add_argument("--lookback-hours", type=int, default=168)
    collect.add_argument("--types", choices=("all", "issues", "discussions"), default="all")
    collect.add_argument(
        "--latest",
        action="store_true",
        help="Ignore checkpoint start and keep only the newest matching records.",
    )
    collect.add_argument(
        "--url",
        help="Exact GitHub issue or pull request issue-comment URL to collect.",
    )
    collect.add_argument("--limit", type=int, default=1)
    collect.add_argument("--bot-logins", help="Comma-separated bot login allowlist")
    collect.add_argument("--max-discussions", type=int, default=200)
    collect.add_argument("--out", help="Output JSONL path")
    collect.add_argument("--checkpoint", default=str(DEFAULT_CHECKPOINT))
    collect.set_defaults(func=command_collect)

    status = subparsers.add_parser("status", help="Show audit checkpoint")
    status.add_argument("--repo", help="Repository in owner/repo format")
    status.add_argument("--checkpoint", default=str(DEFAULT_CHECKPOINT))
    status.add_argument("--json", action="store_true")
    status.set_defaults(func=command_status)

    record = subparsers.add_parser("record", help="Record an audited item")
    record.add_argument("--repo", help="Repository in owner/repo format")
    record.add_argument("--item", required=True, help="Record key from JSONL output")
    record.add_argument(
        "--status",
        required=True,
        choices=(
            "ok",
            "comment-corrected",
            "comment-and-project-fixed",
            "project-fixed",
            "needs-project-fix",
            "skipped",
            "blocked",
        ),
    )
    record.add_argument("--url", required=True)
    record.add_argument("--note", default="")
    record.add_argument("--checkpoint", default=str(DEFAULT_CHECKPOINT))
    record.add_argument("--results", default=str(DEFAULT_RESULTS))
    record.set_defaults(func=command_record)

    return parser


def main() -> int:
    parser = build_parser()
    args = parser.parse_args()
    try:
        return args.func(args)
    except Exception as error:
        print(f"error: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
