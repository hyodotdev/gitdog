    def test_status_counts_latest_status_per_item(self) -> None:
        parser = comment_audit.build_parser()
        with TemporaryDirectory() as temp_dir:
            checkpoint_path = Path(temp_dir) / "checkpoint.json"
            results_path = Path(temp_dir) / "results.jsonl"
            results_path.write_text(
                "\n".join(
                    [
                        json.dumps(
                            {
                                "repo": "hyodotdev/openiap",
                                "item": "issue_comment:1",
                                "status": "project-fixed",
                            }
                        ),
                        json.dumps(
                            {
                                "repo": "hyodotdev/openiap",
                                "item": "issue_comment:1",
                                "status": "comment-and-project-fixed",
                            }
                        ),
                    ]
                )
                + "\n",
                encoding="utf-8",
            )
            checkpoint_path.write_text(
                json.dumps(
                    {
                        "version": 1,
                        "repos": {
                            "hyodotdev/openiap": {
                                "audit_counts": {
                                    "project-fixed": 1,
                                    "comment-and-project-fixed": 1,
                                },
                                "last_audit_results_path": str(results_path),
                            }
                        },
                    }
                ),
                encoding="utf-8",
            )
            args = parser.parse_args(
                [
                    "status",
                    "--repo",
                    "hyodotdev/openiap",
                    "--checkpoint",
                    str(checkpoint_path),
                    "--json",
                ]
            )

            with patch("sys.stdout", new=io.StringIO()) as stdout:
                exit_code = comment_audit.command_status(args)
                output = json.loads(stdout.getvalue())

        self.assertEqual(exit_code, 0)
        self.assertEqual(output["audit_counts"], {"comment-and-project-fixed": 1})

