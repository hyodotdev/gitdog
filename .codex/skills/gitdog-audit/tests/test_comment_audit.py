    def test_latest_counts_skip_malformed_jsonl_entries(self) -> None:
        with TemporaryDirectory() as temp_dir:
            results_path = Path(temp_dir) / "results.jsonl"
            results_path.write_text(
                "\n".join(
                    [
                        "[]",
                        json.dumps(
                            {
                                "repo": ["hyodotdev/openiap"],
                                "item": "issue_comment:1",
                                "status": "ok",
                            }
                        ),
                        json.dumps(
                            {
                                "repo": "hyodotdev/openiap",
                                "item": 1,
                                "status": "ok",
                            }
                        ),
                        json.dumps(
                            {
                                "repo": "hyodotdev/openiap",
                                "item": "issue_comment:1",
                                "status": [],
                            }
                        ),
                        json.dumps(
                            {
                                "repo": "hyodotdev/openiap",
                                "item": "issue_comment:2",
                                "status": "ok",
                            }
                        ),
                    ]
                )
                + "\n",
                encoding="utf-8",
            )

            counts = comment_audit.latest_repo_audit_counts(
                results_path,
                "hyodotdev/openiap",
            )
            directory_counts = comment_audit.latest_repo_audit_counts(
                Path(temp_dir),
                "hyodotdev/openiap",
            )

        self.assertEqual(counts, {"ok": 1})
        self.assertEqual(directory_counts, {})

