import { describe, it, expect, beforeEach } from "vitest";

/**
 * Author Mention Tests
 *
 * Test scenarios:
 * 1. First response (answer) mentions issue/discussion author
 * 2. Follow-up response mentions comment author
 * 3. Handles missing author gracefully
 * 4. Author mention is at the beginning of the comment
 */

type TicketType = "issue" | "discussion";
type TicketActionType = "format" | "answer" | "tag_maintainers" | "follow_up";

interface Ticket {
  id: string;
  userId: string;
  repositoryId: string;
  ticketType: TicketType;
  githubNumber: number;
  githubTitle: string;
  githubBody: string;
  githubAuthor?: string;
  createdAt: number;
}

interface TicketAction {
  id: string;
  ticketId: string;
  actionType: TicketActionType;
  proposedChanges?: {
    suggestedResponse?: string;
    author?: string; // For follow_up actions
    commentId?: number;
    commentNodeId?: string;
  };
}

const FOOTER_MESSAGE = "Have more questions? Tag `@gitdogbot` and let me know!";

// Helper function to build comment body (mirrors actual implementation)
function buildCommentBody(ticket: Ticket, ticketAction: TicketAction): string {
  const authorToMention =
    ticketAction.actionType === "follow_up"
      ? ticketAction.proposedChanges?.author
      : ticket.githubAuthor;
  const mentionPrefix = authorToMention ? `@${authorToMention} ` : "";
  return `${mentionPrefix}${ticketAction.proposedChanges?.suggestedResponse}\n\n---\n*🤖 Generated by [gitdog.dev](https://gitdog.dev) · ${FOOTER_MESSAGE}*`;
}

// In-memory mock database
class MockAuthorDatabase {
  private tickets: Map<string, Ticket> = new Map();
  private actions: Map<string, TicketAction> = new Map();
  private nextId = 1;

  reset() {
    this.tickets.clear();
    this.actions.clear();
    this.nextId = 1;
  }

  generateId() {
    return `id_${this.nextId++}`;
  }

  insertTicket(ticket: Omit<Ticket, "id" | "createdAt">): Ticket {
    const id = this.generateId();
    const newTicket: Ticket = { ...ticket, id, createdAt: Date.now() };
    this.tickets.set(id, newTicket);
    return newTicket;
  }

  getTicket(id: string): Ticket | undefined {
    return this.tickets.get(id);
  }

  insertAction(action: Omit<TicketAction, "id">): TicketAction {
    const id = this.generateId();
    const newAction: TicketAction = { ...action, id };
    this.actions.set(id, newAction);
    return newAction;
  }

  getAction(id: string): TicketAction | undefined {
    return this.actions.get(id);
  }
}

let db: MockAuthorDatabase;

beforeEach(() => {
  db = new MockAuthorDatabase();
});

describe("Author Mention in Comments", () => {
  describe("First Response (answer action)", () => {
    it("should mention issue author at the beginning of comment", () => {
      // Given: A ticket with githubAuthor
      const ticket = db.insertTicket({
        userId: "user_1",
        repositoryId: "repo_1",
        ticketType: "issue",
        githubNumber: 42,
        githubTitle: "How to configure authentication?",
        githubBody: "I need help setting up auth",
        githubAuthor: "johndoe",
      });

      const action = db.insertAction({
        ticketId: ticket.id,
        actionType: "answer",
        proposedChanges: {
          suggestedResponse:
            "You can configure authentication by following these steps...",
        },
      });

      // When
      const commentBody = buildCommentBody(ticket, action);

      // Then
      expect(commentBody.startsWith("@johndoe ")).toBe(true);
      expect(commentBody).toContain(
        "You can configure authentication by following these steps...",
      );
      expect(commentBody).toContain("Generated by [gitdog.dev]");
    });

    it("should mention discussion author at the beginning of comment", () => {
      // Given: A discussion ticket with githubAuthor
      const ticket = db.insertTicket({
        userId: "user_1",
        repositoryId: "repo_1",
        ticketType: "discussion",
        githubNumber: 15,
        githubTitle: "Best practices for testing?",
        githubBody: "What are the recommended testing approaches?",
        githubAuthor: "janedoe",
      });

      const action = db.insertAction({
        ticketId: ticket.id,
        actionType: "answer",
        proposedChanges: {
          suggestedResponse: "Here are some best practices for testing...",
        },
      });

      // When
      const commentBody = buildCommentBody(ticket, action);

      // Then
      expect(commentBody.startsWith("@janedoe ")).toBe(true);
      expect(commentBody).toContain("Here are some best practices for testing");
    });

    it("should handle missing author gracefully (no mention)", () => {
      // Given: A ticket without githubAuthor
      const ticket = db.insertTicket({
        userId: "user_1",
        repositoryId: "repo_1",
        ticketType: "issue",
        githubNumber: 10,
        githubTitle: "Bug report",
        githubBody: "Something is broken",
        // githubAuthor is undefined
      });

      const action = db.insertAction({
        ticketId: ticket.id,
        actionType: "answer",
        proposedChanges: {
          suggestedResponse: "Thank you for reporting this issue.",
        },
      });

      // When
      const commentBody = buildCommentBody(ticket, action);

      // Then
      expect(commentBody.startsWith("@")).toBe(false);
      expect(
        commentBody.startsWith("Thank you for reporting this issue."),
      ).toBe(true);
    });
  });

  describe("Follow-up Response (follow_up action)", () => {
    it("should mention comment author (not ticket author) for follow-up", () => {
      // Given: A ticket with one author, follow-up from different author
      const ticket = db.insertTicket({
        userId: "user_1",
        repositoryId: "repo_1",
        ticketType: "issue",
        githubNumber: 42,
        githubTitle: "How to configure authentication?",
        githubBody: "I need help",
        githubAuthor: "original_author",
      });

      const action = db.insertAction({
        ticketId: ticket.id,
        actionType: "follow_up",
        proposedChanges: {
          suggestedResponse: "Based on your follow-up question...",
          author: "commenter_user", // The person who commented, not the original author
          commentId: 12345,
        },
      });

      // When
      const commentBody = buildCommentBody(ticket, action);

      // Then
      expect(commentBody.startsWith("@commenter_user ")).toBe(true);
      expect(commentBody).not.toContain("@original_author");
      expect(commentBody).toContain("Based on your follow-up question");
    });

    it("should handle follow-up without comment author", () => {
      // Given: A follow-up action without author info
      const ticket = db.insertTicket({
        userId: "user_1",
        repositoryId: "repo_1",
        ticketType: "discussion",
        githubNumber: 20,
        githubTitle: "Question about API",
        githubBody: "How does it work?",
        githubAuthor: "ticket_author",
      });

      const action = db.insertAction({
        ticketId: ticket.id,
        actionType: "follow_up",
        proposedChanges: {
          suggestedResponse: "To answer your follow-up...",
          // author is undefined
          commentId: 67890,
        },
      });

      // When
      const commentBody = buildCommentBody(ticket, action);

      // Then
      expect(commentBody.startsWith("@")).toBe(false);
      expect(commentBody.startsWith("To answer your follow-up")).toBe(true);
    });
  });

  describe("Tag Maintainers Action", () => {
    it("should mention ticket author for tag_maintainers action", () => {
      // Given: A ticket requesting code changes
      const ticket = db.insertTicket({
        userId: "user_1",
        repositoryId: "repo_1",
        ticketType: "issue",
        githubNumber: 100,
        githubTitle: "Add dark mode support",
        githubBody: "Please add dark mode",
        githubAuthor: "feature_requester",
      });

      const action = db.insertAction({
        ticketId: ticket.id,
        actionType: "tag_maintainers",
        proposedChanges: {
          suggestedResponse:
            "This feature request has been noted. Maintainers have been notified.",
        },
      });

      // When
      const commentBody = buildCommentBody(ticket, action);

      // Then
      expect(commentBody.startsWith("@feature_requester ")).toBe(true);
      expect(commentBody).toContain("Maintainers have been notified");
    });
  });

  describe("Comment Body Format", () => {
    it("should have correct structure: @mention + response + footer", () => {
      // Given
      const ticket = db.insertTicket({
        userId: "user_1",
        repositoryId: "repo_1",
        ticketType: "issue",
        githubNumber: 1,
        githubTitle: "Test",
        githubBody: "Test body",
        githubAuthor: "testuser",
      });

      const action = db.insertAction({
        ticketId: ticket.id,
        actionType: "answer",
        proposedChanges: {
          suggestedResponse: "This is the AI response.",
        },
      });

      // When
      const commentBody = buildCommentBody(ticket, action);

      // Then
      const lines = commentBody.split("\n");
      // First line should start with @mention and contain response
      expect(lines[0].startsWith("@testuser This is the AI response.")).toBe(
        true,
      );
      // Should have separator
      expect(commentBody).toContain("---");
      // Should have footer
      expect(commentBody).toContain("Generated by [gitdog.dev]");
      expect(commentBody).toContain(FOOTER_MESSAGE);
    });

    it("should not add extra space when no author", () => {
      // Given
      const ticket = db.insertTicket({
        userId: "user_1",
        repositoryId: "repo_1",
        ticketType: "issue",
        githubNumber: 1,
        githubTitle: "Test",
        githubBody: "Test body",
        // No githubAuthor
      });

      const action = db.insertAction({
        ticketId: ticket.id,
        actionType: "answer",
        proposedChanges: {
          suggestedResponse: "Response without mention.",
        },
      });

      // When
      const commentBody = buildCommentBody(ticket, action);

      // Then
      expect(commentBody.startsWith("Response without mention.")).toBe(true);
      expect(commentBody.startsWith(" Response")).toBe(false); // No leading space
    });
  });

  describe("Edge Cases", () => {
    it("should handle author with special characters", () => {
      // Given: GitHub allows hyphens and numbers in usernames
      const ticket = db.insertTicket({
        userId: "user_1",
        repositoryId: "repo_1",
        ticketType: "issue",
        githubNumber: 1,
        githubTitle: "Test",
        githubBody: "Test",
        githubAuthor: "user-name-123",
      });

      const action = db.insertAction({
        ticketId: ticket.id,
        actionType: "answer",
        proposedChanges: {
          suggestedResponse: "Hello!",
        },
      });

      // When
      const commentBody = buildCommentBody(ticket, action);

      // Then
      expect(commentBody.startsWith("@user-name-123 ")).toBe(true);
    });

    it("should handle empty string author as no mention", () => {
      // Given
      const ticket = db.insertTicket({
        userId: "user_1",
        repositoryId: "repo_1",
        ticketType: "issue",
        githubNumber: 1,
        githubTitle: "Test",
        githubBody: "Test",
        githubAuthor: "", // Empty string
      });

      const action = db.insertAction({
        ticketId: ticket.id,
        actionType: "answer",
        proposedChanges: {
          suggestedResponse: "Response here.",
        },
      });

      // When
      const commentBody = buildCommentBody(ticket, action);

      // Then
      // Empty string is falsy, so no mention
      expect(commentBody.startsWith("Response here.")).toBe(true);
    });

    it("should handle multiline AI response correctly", () => {
      // Given
      const ticket = db.insertTicket({
        userId: "user_1",
        repositoryId: "repo_1",
        ticketType: "issue",
        githubNumber: 1,
        githubTitle: "Test",
        githubBody: "Test",
        githubAuthor: "multiline_user",
      });

      const action = db.insertAction({
        ticketId: ticket.id,
        actionType: "answer",
        proposedChanges: {
          suggestedResponse: "Line 1\n\nLine 2\n\n```js\ncode here\n```",
        },
      });

      // When
      const commentBody = buildCommentBody(ticket, action);

      // Then
      expect(commentBody.startsWith("@multiline_user Line 1")).toBe(true);
      expect(commentBody).toContain("Line 2");
      expect(commentBody).toContain("```js");
    });
  });
});

