const EXECUTION_MARKER_PREFIX = "gitdog-execution:";
const EXECUTION_MARKER_PATTERN =
  /<!--\s*gitdog-execution:[0-9a-f-]{36}\s*-->/gi;
const EXECUTION_MARKER_CAPTURE_PATTERN =
  /<!--\s*gitdog-execution:([0-9a-f-]{36})\s*-->/gi;

export const CLAIMED_EXECUTION_RECOVERY_LEASE_MS = 15 * 60 * 1_000;
export const CLAIMED_EXECUTION_RECOVERY_TTL_MS = 24 * 60 * 60 * 1_000;
export const CLAIMED_EXECUTION_RECOVERY_GRACE_MS = 2 * 60 * 1_000;
export const DISCONNECT_EXECUTION_RECONCILIATION_TTL_MS = 15 * 60 * 1_000;

export function buildExecutionMarker(idempotencyKey: string): string {
  return `<!-- ${EXECUTION_MARKER_PREFIX}${idempotencyKey} -->`;
}

export function attachExecutionMarker(
  body: string,
  idempotencyKey: string,
): string {
  return `${buildExecutionMarker(idempotencyKey)}\n${body}`;
}

export function buildMarkedResponseComment(
  suggestedResponse: string,
  authorToMention: string | undefined,
  footerMessage: string,
  idempotencyKey: string,
): string {
  const mentionPrefix = authorToMention ? `@${authorToMention} ` : "";
  return attachExecutionMarker(
    `${mentionPrefix}${suggestedResponse}\n\n---\n*🤖 Generated by [gitdog.dev](https://gitdog.dev) · ${footerMessage}*`,
    idempotencyKey,
  );
}

export function stripExecutionMarkers(body: string): string {
  return body.replace(EXECUTION_MARKER_PATTERN, "").trim();
}

export function extractExecutionMarkerKey(body: string): string | null {
  const matches = [...body.matchAll(EXECUTION_MARKER_CAPTURE_PATTERN)];
  return matches.length === 1 ? matches[0][1].toLowerCase() : null;
}

export function classifyFormatExecutionReconciliation(args: {
  liveState: string;
  liveTitle: string;
  liveBody: string;
  originalTitle: string;
  originalBody: string;
  expectedTitle: string;
  expectedBody: string;
  marker: string;
}): "already_applied" | "safe_to_apply" | "conflict" {
  if (
    args.liveBody.includes(args.marker) ||
    (args.liveTitle === args.expectedTitle &&
      args.liveBody === args.expectedBody)
  ) {
    return "already_applied";
  }
  if (
    args.liveState === "open" &&
    args.liveTitle === args.originalTitle &&
    args.liveBody === args.originalBody
  ) {
    return "safe_to_apply";
  }
  return "conflict";
}
